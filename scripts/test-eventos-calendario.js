const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('js/calendar-events.js', 'utf8'), ctx);
const { cumpleEn, festivos, nacimientoValido, hoyCentro } = ctx.window.CalendarioEventos;
assert.equal(cumpleEn({ fecha_nacimiento: '2000-02-29' }, 2027).dia, '2027-02-28');
assert.equal(cumpleEn({ fecha_nacimiento: '2000-02-29' }, 2028).dia, '2028-02-29');
assert.equal(cumpleEn({ fecha_nacimiento: '2000-01-01' }, 2026).cumple_edad, 26);
assert.equal(cumpleEn({ fecha_nacimiento: null }, 2026), null);
assert.equal(nacimientoValido('2026-02-30'), false);
assert.equal(nacimientoValido('2099-01-01'), false);
assert.match(hoyCentro(), /^\d{4}-\d{2}-\d{2}$/);
const fiestas = festivos(2026);
assert(fiestas.some(f => f.dia === '2026-02-02' && f.oficial));
assert(fiestas.some(f => f.dia === '2026-03-16' && f.oficial));
assert(fiestas.some(f => f.dia === '2026-11-16' && f.oficial));
assert(fiestas.some(f => f.dia === '2026-11-02' && !f.oficial));
assert(!fiestas.some(f => f.dia === '2026-10-01'));
assert(festivos(2030).some(f => f.dia === '2030-10-01' && f.oficial));
console.log('Cumpleaños, años bisiestos, fechas inválidas y festivos móviles correctos.');
